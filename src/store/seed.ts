export interface SeedOptions {
  clock?: Clock;
}

export async function seedDemoData(
  repository: LeadRepository,
  options: SeedOptions = {},
): Promise<LeadStoreState> {
  const clock = options.clock ?? createFixedClock(DEMO_NOW_ISO);
  const state = createSeedState(clock.now());
  await repository.replaceAll(state);
  return state;
}

export async function resetDemoData(
  repository: LeadRepository,
  options: SeedOptions = {},
): Promise<LeadStoreState> {
  return seedDemoData(repository, options);
}
